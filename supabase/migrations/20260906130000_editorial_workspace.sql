create schema if not exists private;
revoke all on schema private from public, anon;

create table if not exists public.editorial_members (
    user_id uuid primary key references auth.users(id) on delete cascade,
    display_name text not null check (char_length(display_name) between 2 and 100),
    role text not null check (role in ('editor', 'approver', 'admin')),
    active boolean not null default true,
    created_by uuid references auth.users(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.editorial_assignments (
    record_id text primary key check (record_id ~ '^(visa-summary|visa-matrix|border|park-fee|emergency|travel-advisory):[a-z0-9-]+$'),
    owner_id uuid not null references public.editorial_members(user_id),
    approver_id uuid references public.editorial_members(user_id),
    status text not null default 'draft' check (status in ('draft', 'in-review', 'changes-requested', 'approved', 'published', 'blocked')),
    approved_at timestamptz,
    published_at timestamptz,
    updated_by uuid not null references auth.users(id),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (approver_id is null or approver_id <> owner_id),
    check (status not in ('approved', 'published') or (approver_id is not null and approved_at is not null)),
    check (status <> 'published' or published_at is not null)
);

create table if not exists public.editorial_corrections (
    id uuid primary key default gen_random_uuid(),
    record_id text not null check (record_id ~ '^(visa-summary|visa-matrix|border|park-fee|emergency|travel-advisory):[a-z0-9-]+$'),
    owner_id uuid not null references public.editorial_members(user_id),
    status text not null default 'open' check (status in ('open', 'investigating', 'resolved', 'rejected')),
    summary text not null check (char_length(summary) between 5 and 1000),
    resolution text check (resolution is null or char_length(resolution) between 5 and 2000),
    opened_by uuid not null references auth.users(id),
    opened_at timestamptz not null default now(),
    closed_at timestamptz,
    updated_at timestamptz not null default now(),
    check (status not in ('resolved', 'rejected') or (closed_at is not null and resolution is not null)),
    check (closed_at is null or closed_at >= opened_at)
);

create table if not exists public.editorial_events (
    id bigint generated by default as identity primary key,
    record_id text not null check (record_id ~ '^(visa-summary|visa-matrix|border|park-fee|emergency|travel-advisory):[a-z0-9-]+$'),
    actor_id uuid references auth.users(id) on delete set null,
    event_type text not null check (char_length(event_type) between 1 and 80),
    detail jsonb not null default '{}'::jsonb check (jsonb_typeof(detail) = 'object'),
    created_at timestamptz not null default now()
);

create index if not exists editorial_assignments_owner_idx on public.editorial_assignments (owner_id, updated_at desc);
create index if not exists editorial_assignments_approver_idx on public.editorial_assignments (approver_id, updated_at desc);
create index if not exists editorial_corrections_record_idx on public.editorial_corrections (record_id, status, opened_at desc);
create index if not exists editorial_corrections_owner_idx on public.editorial_corrections (owner_id, status, updated_at desc);
create index if not exists editorial_events_record_idx on public.editorial_events (record_id, created_at desc);

alter table public.editorial_members enable row level security;
alter table public.editorial_assignments enable row level security;
alter table public.editorial_corrections enable row level security;
alter table public.editorial_events enable row level security;

create or replace function private.current_editorial_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
    select em.role
    from public.editorial_members em
    where em.user_id = (select auth.uid()) and em.active
    limit 1;
$$;

revoke all on function private.current_editorial_role() from public, anon;
grant usage on schema private to authenticated;
grant execute on function private.current_editorial_role() to authenticated;

