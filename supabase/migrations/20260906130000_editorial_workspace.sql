create or replace function private.guard_editorial_assignment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user uuid := auth.uid();
    v_role text := private.current_editorial_role();
begin
    if v_user is null or v_role is null then raise exception 'Editorial access required'; end if;

    if tg_op = 'INSERT' then
        if v_role <> 'admin' then raise exception 'Editorial administrator access required'; end if;
        if new.status not in ('draft', 'blocked') then
            raise exception 'New assignments must begin as draft or blocked';
        end if;
        new.created_at := now();
        new.updated_by := v_user;
    elsif tg_op = 'UPDATE' then
        if new.record_id is distinct from old.record_id then
            raise exception 'Editorial record IDs cannot be changed';
        end if;
        if new.created_at is distinct from old.created_at
            or new.approved_at is distinct from old.approved_at
            or new.published_at is distinct from old.published_at
            or new.updated_by is distinct from old.updated_by then
            raise exception 'Editorial workflow timestamps and actors are database managed';
        end if;
        if (new.owner_id is distinct from old.owner_id or new.approver_id is distinct from old.approver_id) then
            if v_role <> 'admin' then
                raise exception 'Only an editorial administrator can change assignment ownership';
            end if;
            if new.status in ('approved', 'published') then
                raise exception 'Reset approval before changing assignment ownership';
            end if;
        end if;
        if new.status is distinct from old.status then
            if new.status in ('approved', 'changes-requested') then
                if v_user is distinct from new.approver_id then
                    raise exception 'Only the assigned independent approver can approve work or request changes';
                end if;
                if old.status not in ('in-review', 'approved', 'changes-requested') then
                    raise exception 'The owner must submit work for review before an approval decision';
                end if;
            elsif new.status = 'published' then
                if v_role <> 'admin' then raise exception 'Editorial administrator access required to publish'; end if;
                if old.status <> 'approved' then raise exception 'Independent approval is required before publication'; end if;
            elsif new.status in ('draft', 'in-review', 'blocked') then
                if v_role <> 'admin' and v_user <> old.owner_id then
                    raise exception 'Owners can submit work for review or mark it blocked';
                end if;
            end if;
        elsif v_role <> 'admin' and v_user <> old.owner_id and v_user is distinct from old.approver_id then
            raise exception 'Assignment participant access required';
        end if;
        new.updated_by := v_user;
        new.updated_at := now();
    elsif tg_op = 'DELETE' then
        if v_role <> 'admin' then raise exception 'Editorial administrator access required'; end if;
        return old;
    end if;

    if not exists (
        select 1 from public.editorial_members
        where user_id = new.owner_id and active and role in ('editor', 'admin')
    ) then raise exception 'Assignment owner must be an active editor or administrator'; end if;
    if new.approver_id is not null and not exists (
        select 1 from public.editorial_members
        where user_id = new.approver_id and active and role in ('approver', 'admin')
    ) then raise exception 'Assignment approver must be an active approver or administrator'; end if;

    if new.status in ('approved', 'published') then
        new.approved_at := coalesce(new.approved_at, now());
    else
        new.approved_at := null;
    end if;
    if new.status = 'published' then
        new.published_at := coalesce(new.published_at, now());
    else
        new.published_at := null;
    end if;
    return new;
end;
$$;

create or replace function private.audit_editorial_assignment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_record_id text;
    v_previous_status text;
    v_status text;
begin
    if tg_op = 'DELETE' then
        v_record_id := old.record_id;
        v_previous_status := old.status;
        v_status := null;
    elsif tg_op = 'INSERT' then
        v_record_id := new.record_id;
        v_previous_status := null;
        v_status := new.status;
    else
        v_record_id := new.record_id;
        v_previous_status := old.status;
        v_status := new.status;
    end if;
    insert into public.editorial_events (record_id, actor_id, event_type, detail)
    values (
        v_record_id,
        auth.uid(),
        case when tg_op = 'INSERT' then 'assignment-created' when tg_op = 'DELETE' then 'assignment-removed' else 'assignment-updated' end,
        jsonb_build_object(
            'previousStatus', v_previous_status,
            'status', v_status
        )
    );
    if tg_op = 'DELETE' then return old; end if;
    return new;
end;
$$;

create or replace function private.guard_editorial_correction()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user uuid := auth.uid();
    v_role text := private.current_editorial_role();
begin
    if v_user is null or v_role is null then raise exception 'Editorial access required'; end if;

    if tg_op = 'INSERT' then
        if v_role <> 'admin' and new.owner_id <> v_user then
            raise exception 'Editors may only open corrections they own';
        end if;
        new.opened_by := v_user;
        new.opened_at := now();
    elsif tg_op = 'UPDATE' then
        if v_role <> 'admin' then
            if old.owner_id <> v_user then raise exception 'Correction owner access required'; end if;
            if new.record_id is distinct from old.record_id
                or new.owner_id is distinct from old.owner_id
                or new.opened_by is distinct from old.opened_by
                or new.opened_at is distinct from old.opened_at then
                raise exception 'Only an editorial administrator can reassign a correction';
            end if;
        end if;
        new.updated_at := now();
    elsif tg_op = 'DELETE' then
        if v_role <> 'admin' then raise exception 'Editorial administrator access required'; end if;
        return old;
    end if;

    if new.status in ('resolved', 'rejected') then
        if new.resolution is null or char_length(new.resolution) < 5 then
            raise exception 'A correction resolution is required before closure';
        end if;
        new.closed_at := coalesce(new.closed_at, now());
    else
        new.closed_at := null;
    end if;
    return new;
end;
$$;

create or replace function private.audit_editorial_correction()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_record_id text;
    v_correction_id uuid;
    v_status text;
begin
    if tg_op = 'DELETE' then
        v_record_id := old.record_id;
        v_correction_id := old.id;
        v_status := null;
    else
        v_record_id := new.record_id;
        v_correction_id := new.id;
        v_status := new.status;
    end if;
    insert into public.editorial_events (record_id, actor_id, event_type, detail)
    values (
        v_record_id,
        auth.uid(),
        case when tg_op = 'INSERT' then 'correction-opened' when tg_op = 'DELETE' then 'correction-removed' else 'correction-updated' end,
        jsonb_build_object(
            'correctionId', v_correction_id,
            'status', v_status
        )
    );
    if tg_op = 'DELETE' then return old; end if;
    return new;
end;
$$;

